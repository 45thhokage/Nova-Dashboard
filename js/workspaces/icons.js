/**
 * Inline SVG string for an icon name. Unknown names fall back to a globe.
 * `grip` renders filled dots; everything else is stroked.
 */
export function icon(name, size = 20, strokeWidth = 1.75) {
  const body = PATHS[name] || PATHS.globe;
  if (name === 'grip') {
    return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">${body}</svg>`;
  }
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}
